import numpy as np

# Create arrays
a = np.array([10, 20, 30, 40])
b = np.array([1, 2, 3, 4])

# Arithmetic Operations
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Element-wise power
print("Power (a ** b):", a ** b)

# Modulo operation
print("Modulo (a % b):", a % b)
