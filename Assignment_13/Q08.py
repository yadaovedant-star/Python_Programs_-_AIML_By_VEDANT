import numpy as np

# Create a 4x4 matrix of random integers between 1 and 100
J1 = np.random.randint(1, 101, (4, 4))

# Print matrix and its properties
print("Q8 - Matrix J1 (4x4 random integers 1 to 100):\n", J1)
print("Shape:", J1.shape)
print("Dimension (ndim):", J1.ndim)
print("Total number of elements (size):", J1.size)
print("Data type (dtype):", J1.dtype)
print("Minimum value in J1:", J1.min())
print("Maximum value in J1:", J1.max())









