import numpy as np

# a) 10 equally spaced numbers between 0 and 5
VSYNC1 = np.linspace(0, 5, 10)

# b) 15 equally spaced numbers between 10 and 10
VSYNC2 = np.linspace(10, 10, 15)

# Printing arrays and their lengths
print("Array VSYNC1 (10 numbers between 0 and 5):\n", VSYNC1)
print("Length:", len(VSYNC1))

print("\nArray VSYNC2 (15 numbers between 10 and 10):\n", VSYNC2)
print("Length:", len(VSYNC2))



