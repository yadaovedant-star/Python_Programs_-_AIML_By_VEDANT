import numpy as np

# a) Create a 1D array
array1 = np.array([89, 50, 34, 55, 20])

# b) Create a 2D array (3x3)
array2 = np.array([[99, 21, 68],
                    [34, 45, 12],
                    [77, 88, 99]])

# Print arrays, shape, and dtype
print("1D Array:\n", array1)
print("Shape:", array1.shape)
print("Data Type:", array1.dtype)

print("\n2D Array:\n", array2)
print("Shape:", array2.shape)
print("Data Type:", array2.dtype)
